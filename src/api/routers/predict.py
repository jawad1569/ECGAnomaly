from fastapi import APIRouter, HTTPException
from pydantic import BaseModel
import numpy as np
from typing import List, Optional
from src.utils.model_loader import predict_ecg_signal
from src.utils.features import validate_signal

router = APIRouter()


class ECGSignalInput(BaseModel):
    """Input model for ECG signal prediction.

    The signal should be a 2D array where:
    - First dimension: time steps
    - Second dimension: 12 ECG channels (I, II, III, aVR, aVL, aVF, V1-V6)
    """

    signal: List[List[float]]  # Shape: (time_steps, 12)
    ecg_id: Optional[int] = None  # Optional patient ID for tracking


class ECGSimpleInput(BaseModel):
    """Simple input for backward compatibility (single value)."""

    signal_value: float


@router.post("/predict", tags=["Model"])
def predict_ecg(input_data: ECGSignalInput):
    """
    Predict ECG classification using the MLflow-registered model.

    Expected input format:
    {
        "signal": [[ch1_t1, ch2_t1, ..., ch12_t1],
                   [ch1_t2, ch2_t2, ..., ch12_t2],
                   ...],
        "ecg_id": 123  # optional
    }

    Returns the predicted class (Normal/Abnormal), confidence score,
    per-class probabilities, model version, and a plain-text explanation
    generated by lead-masking (blanking one lead at a time).
    """
    import time
    from datetime import datetime

    start_time = time.time()
    request_id = f"req_{int(time.time() * 1000)}"

    try:
        print("\n" + "=" * 60)
        print(
            f"PREDICTION REQUEST [{request_id}] at {datetime.now().strftime('%H:%M:%S')}"
        )
        print(
            f"   Signal: {len(input_data.signal)} x "
            f"{len(input_data.signal[0]) if input_data.signal else 0}"
        )
        print("=" * 60)

        # Convert to numpy array
        signal_array = np.array(input_data.signal)
        print(f"Signal converted: {signal_array.shape}")

        # Validate shape
        if len(signal_array.shape) != 2:
            raise HTTPException(
                status_code=400,
                detail=(
                    f"Signal must be a 2D array (time_steps, 12). "
                    f"Got shape: {signal_array.shape}"
                ),
            )

        if signal_array.shape[1] != 12:
            raise HTTPException(
                status_code=400,
                detail=(
                    f"Signal must have 12 channels. "
                    f"Got {signal_array.shape[1]} channels"
                ),
            )

        try:
            validate_signal(signal_array)
        except ValueError as ve:
            raise HTTPException(status_code=400, detail=str(ve))

        # Run model
        print("Running ML model...")
        model_start = time.time()
        prediction = predict_ecg_signal(signal_array)
        model_time = time.time() - model_start
        predicted_class = prediction["predicted_class"]
        print(
            f"Prediction: {predicted_class} "
            f"(confidence: {prediction['confidence']:.1%}) in {model_time:.2f}s"
        )

        # Explanation via lead-masking
        explanation = _explain_by_lead_masking(signal_array, predicted_class, prediction)

        total_time = time.time() - start_time
        print("=" * 60)
        print(f"COMPLETE in {total_time:.2f}s - Prediction: {predicted_class}")
        print("=" * 60 + "\n")

        return {
            "ecg_id": input_data.ecg_id,
            "signal_shape": list(signal_array.shape),
            "prediction": predicted_class,
            "confidence": prediction["confidence"],
            "probabilities": prediction["probabilities"],
            "class_index": prediction["class_index"],
            "model_version": prediction.get("model_version", "v1"),
            "explanation": explanation,
        }

    except HTTPException:
        raise
    except Exception as e:
        error_detail = str(e)
        elapsed = time.time() - start_time
        print("=" * 60)
        print(f"ERROR after {elapsed:.2f}s: {error_detail}")
        print("=" * 60 + "\n")
        raise HTTPException(status_code=500, detail=f"Prediction error: {error_detail}")


def _explain_by_lead_masking(
    signal_array: np.ndarray, predicted_class: str, base_prediction: dict
) -> str:
    """Generate a plain-text explanation by masking one lead at a time.

    For each of the 12 leads, replace it with zeros and re-run the model to
    measure how much the confidence drops.  The leads whose removal causes the
    largest drop are the most influential in this prediction.
    """
    LEAD_NAMES = [
        "I", "II", "III", "aVR", "aVL", "aVF",
        "V1", "V2", "V3", "V4", "V5", "V6",
    ]
    base_conf = base_prediction["confidence"]
    drops = {}

    for lead_idx, lead_name in enumerate(LEAD_NAMES):
        masked = signal_array.copy()
        masked[:, lead_idx] = 0.0
        try:
            masked_pred = predict_ecg_signal(masked)
            drops[lead_name] = base_conf - masked_pred["confidence"]
        except Exception:
            drops[lead_name] = 0.0

    top_leads = sorted(drops, key=drops.get, reverse=True)[:3]
    top_str = ", ".join(top_leads)

    return (
        f"The ECG is classified as {predicted_class} "
        f"(confidence {base_conf:.0%}). "
        f"The most influential leads are: {top_str}. "
        "Please consult a cardiologist for clinical interpretation."
    )


@router.post("/explain", tags=["Model"])
def explain_ecg(input_data: ECGSignalInput):
    """
    Return per-lead importance scores for the given ECG signal by masking
    one lead at a time and measuring the resulting change in confidence.
    """
    signal_array = np.array(input_data.signal)

    if len(signal_array.shape) != 2 or signal_array.shape[1] != 12:
        raise HTTPException(
            status_code=400,
            detail="Signal must be a 2D array with shape (time_steps, 12).",
        )

    base_prediction = predict_ecg_signal(signal_array)
    base_conf = base_prediction["confidence"]

    LEAD_NAMES = [
        "I", "II", "III", "aVR", "aVL", "aVF",
        "V1", "V2", "V3", "V4", "V5", "V6",
    ]
    lead_importance = {}
    for lead_idx, lead_name in enumerate(LEAD_NAMES):
        masked = signal_array.copy()
        masked[:, lead_idx] = 0.0
        try:
            masked_pred = predict_ecg_signal(masked)
            lead_importance[lead_name] = round(base_conf - masked_pred["confidence"], 4)
        except Exception:
            lead_importance[lead_name] = 0.0

    return {
        "ecg_id": input_data.ecg_id,
        "prediction": base_prediction["predicted_class"],
        "confidence": base_conf,
        "model_version": base_prediction.get("model_version", "v1"),
        "lead_importance": lead_importance,
    }


@router.post("/predict/simple", tags=["Model"])
def predict_ecg_simple(input_data: ECGSimpleInput):
    """
    Simple mock endpoint for backward compatibility.
    Use /predict for real model inference.
    """
    result = "Normal" if input_data.signal_value < 0.5 else "Abnormal"
    return {
        "input_signal": input_data.signal_value,
        "prediction": result,
        "note": "This is a mock endpoint. Use /predict for real model inference.",
    }
